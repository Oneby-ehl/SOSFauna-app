let cachedCatalog: Catalog | undefined;
let animalTerms = new Map<string, string[]>();
export function getEnglishFaqKeywords(source: readonly string[], texts: Catalog): string[] {
  if (cachedCatalog !== texts) {
    animalTerms = new Map();
    const es = getCatalog("es");
    for (const id of Object.keys(es.faqAnimalNames) as (keyof Catalog["faqAnimalNames"])[]) {
      const translated = [texts.faqAnimalNames[id], ...texts.faqAnimalAliases[id].split("|")];
      for (const original of [es.faqAnimalNames[id], ...es.faqAnimalAliases[id].split("|")]) {
        if (original) animalTerms.set(normalizeAnimalSearchText(original), translated);
      }
    }
    cachedCatalog = texts;
  }
  return Array.from(new Set(source.flatMap(term =>
    animalTerms.get(normalizeAnimalSearchText(term)) ?? terms.get(normalizeAnimalSearchText(term)) ?? [term],
  )));
}
